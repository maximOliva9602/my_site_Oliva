/* ============================================================
   service-groups.js — ЄДИНІ правила розкладання послуг по групах.
   Використовують і сайт (index.html), і онлайн-запис (booking.html).
   Раніше логіка була лише в booking.html, а сайт групував за своїми
   правилами — через це ті самі послуги потрапляли в різні розділи.
   ============================================================ */
(function (global) {
  "use strict";

  var GROUPS = [
    { key: "general", name: "Масажі",           sub: "Оздоровлення та відновлення для тіла і обличчя" },
    { key: "spa2",    name: "SPA для двох",      sub: "Парні масажі та SPA для вас і ваших близьких" },
    { key: "spa1",    name: "SPA для одного",    sub: "Індивідуальний релакс та глибоке розслаблення" },
    { key: "body",    name: "Корекція фігури",   sub: "Моделювання та покращення контурів тіла" },
    { key: "extra",   name: "Додаткові послуги", sub: "Додатковий догляд для краси та гармонії" },
  ];
  /* Категорія послуги (parseName().cat) → група. Керується тут; якщо власник
     додасть нову послугу з новою назвою, її категорія без пари в цьому
     словнику потрапить у "Додаткові послуги" (див. дефолт у groupOf). */
  var GROUP_MAP = {
    "Загально-оздоровчий масаж": "general", "Антистресовий масаж": "general",
    "Масаж спини": "general", "Масаж шийно-комірцевої зони": "general",
    "Спортивний масаж": "general", "Міофасціальний масаж": "general",
    "Relax масаж": "general", "Медовий масаж": "general",
    "Масаж для вагітних": "general", "Масаж голови": "general",
    "Масаж стоп": "general", "Вісцеральний масаж": "general",
    "Дитячий масаж": "general",
    // Масажі обличчя (перенесено зі «SPA для одного» до «Масажі»)
    "Класичний масаж обличчя": "general", "Антивіковий масаж обличчя": "general",
    "Пластичний масаж обличчя": "general", "Скульптуруючий масаж обличчя": "general",
    "Лімфодренажний масаж обличчя": "general", "Relax масаж обличчя": "general",
    "Моделюючий масаж обличчя": "general", "Гуа-ша обличчя": "general",
    "Кобідо": "general", "Букальний масаж": "general",

    "Парний масаж": "spa2",
    'Тепловий SPA-ритуал "Глибоке прогрівання для двох"': "spa2",
    "Масаж в чотири руки": "spa2",
    'Масаж гарячим камінням для двох "Stone therapy"': "spa2",

    "Паріння у фітобочці": "spa1", 'SPA Ритуал "Фіто-оновлення тіла"': "spa1",
    "Масаж гарячим камінням": "spa1",

    "Антицелюлітний масаж": "body", "Моделюючий масаж": "body",
    "Лімфодренажний масаж": "body", "Вакуумно-баночний масаж": "body",
    "Апаратно-вакуумний масаж": "body",
    "Обгортання Amore Shemen (гаряче)": "body",
    "Обгортання Amore Shemen (холодне)": "body",
    "Обгортання Bruno Vassari Detox": "body",
    "Гаряче обгортання SPA Seaweed": "body",
    "Гаряча експрес-трансформація тіла": "body",
    "Гаряче моделювання тіла": "body", "Холодне моделювання тіла": "body",
    "Сольове обгортання": "body",

    "Кінезіотейпування": "extra",
  };
  function groupOf(cat) { return GROUP_MAP[cat] || "extra"; }
  /* services.category (редагується в /admin) може перекрити автоматичне
     групування за назвою — досить записати туди одну з 5 назв групи.
     Порожнє/незнайоме значення — як і раніше, групуємо за GROUP_MAP. */
  /* Категорії, якими власник реально користується в CRM. Вони не збігаються
     з назвами 5 груп, тому без цієї мапи КОЖНА нова послуга падала в
     «Додаткові послуги», доки хтось не допише її назву в GROUP_MAP вручну. */
  var CATEGORY_MAP = {
    "SPA-масажі для двох": "spa2",
    "SPA-ритуали": "spa1",
    "Комплекси": "spa1",
    "Прайс Майстер": "general",
    "Прайс Топ Майстер": "general",
  };
  function resolveGroup(s, parsedCat) {
    var raw = (s.category || "").trim();
    // 1) категорія дослівно дорівнює назві групи — найявніше побажання власника
    var g = GROUPS.filter(function (x) { return x.name === raw; })[0];
    if (g) return g.key;
    // 2) точна назва послуги
    if (GROUP_MAP[parsedCat]) return GROUP_MAP[parsedCat];
    // 3) «для двох» / «парний» у назві — це завжди SPA для двох
    if (/для двох|парн/i.test(parsedCat)) return "spa2";
    // 4) категорія з CRM
    if (CATEGORY_MAP[raw]) return CATEGORY_MAP[raw];
    return "extra";
  }

  function parseName(name) {
    var lm = name.match(/\((Топ Майстер|Майстер)\)/);
    var level = lm ? lm[1] : null;
    var dm = name.match(/(\d+)\s*хв/);
    var dur = dm ? parseInt(dm[1]) : null;
    if (!dur) { var gm = name.match(/(\d+)\s*год/); if (gm) dur = parseInt(gm[1]) * 60; }
    var cat = name
      .replace(/\s*\(Топ Майстер\)/, "").replace(/\s*\(Майстер\)/, "")
      /* Тривалість у дужках в кінці — «Фіто-оновлення тіла для двох (130 хв)».
         Без цього вона лишалась у назві категорії: картка показувала «(130 хв)»,
         а варіанти тієї самої послуги на 90 і 130 хв не склеювались в одну
         картку з вибором тривалості. Дужки не в кінці (Amore Shemen (гаряче))
         не чіпаємо — це частина назви. */
      .replace(/\s*\(\s*\d+\s*(?:хв|год)\s*\)\s*$/, "")
      .replace(/\s+\d+\s*хв$/, "").replace(/\s+\d+\s*год.*$/, "").trim();
    return { cat: cat, level: level, dur: dur };
  }

  global.OlivaServiceGroups = {
    GROUPS: GROUPS, GROUP_MAP: GROUP_MAP, CATEGORY_MAP: CATEGORY_MAP,
    parseName: parseName, groupOf: groupOf, resolveGroup: resolveGroup
  };
})(window);
